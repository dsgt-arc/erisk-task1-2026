"""
Interviewer agent: Generates natural, empathetic interview questions.

Supports two modes:
- LLM-only: all questions generated by the language model (default)
- Tree-first: precomputed questions from dialogue tree, LLM fallback
"""

import json
import random
import re
from pathlib import Path
from typing import Optional

import llm
from models import InterviewState, OrchestratorGuidance

_TRANSITIONS = [
    "That makes sense.",
    "Thank you for sharing that.",
    "I appreciate you telling me that.",
    "I hear you.",
    "That sounds really tough.",
    "Thanks for being so open.",
]


class InterviewerAgent:
    """
    LLM-based interviewer with optional dialogue tree support.

    When tree_bank is provided, tries precomputed questions first
    and falls back to LLM generation when no good tree match exists.
    """

    def __init__(
        self,
        model: Optional[str] = None,
        prompt_path: Optional[Path] = None,
        temperature: float = 0.7,
        tree_bank: Optional[dict] = None,
        tree_threshold: float = 1.5,
    ):
        self.model = model
        self.temperature = temperature
        self.tree_bank = tree_bank
        self.tree_threshold = tree_threshold

        # Tree navigation state (reset per interview via reset_tree)
        self._used_ids: set = set()
        self._current_node: Optional[dict] = None

        if prompt_path is None:
            prompt_path = (
                Path(__file__).parent.parent.parent / "prompts" / "interviewer.md"
            )
        self.base_prompt = prompt_path.read_text()

    def reset_tree(self):
        """Reset tree state for a new interview."""
        self._used_ids = set()
        self._current_node = None

    def generate_message(
        self,
        state: InterviewState,
        guidance: OrchestratorGuidance,
    ) -> tuple:
        """
        Generate the interviewer's next message.

        Returns:
            (message_text, source) where source is "tree" or "llm"
        """
        if self.tree_bank and not guidance.wrap_up:
            tree_q = self._try_tree_question(state, guidance)
            if tree_q:
                return tree_q, "tree"

        return self._generate_llm_message(state, guidance), "llm"

    def _try_tree_question(self, state, guidance):
        """Try to get a question from the dialogue tree."""
        import dialogue_tree

        # If we have a current node and the persona just responded, try followup
        if self._current_node and state.messages:
            last_msg = state.messages[-1]
            if last_msg.role == "persona":
                followup = dialogue_tree.get_followup(
                    self.tree_bank, last_msg.content,
                    self._current_node, self.tree_threshold,
                )
                if followup:
                    self._used_ids.add(followup["id"])
                    self._current_node = followup
                    transition = random.choice(_TRANSITIONS)
                    return f"{transition} {followup['text']}"

        # Try getting an opener for the focus symptoms
        opener = dialogue_tree.get_opener(
            self.tree_bank, guidance.focus_symptoms, self._used_ids,
        )
        if opener:
            self._used_ids.add(opener["id"])
            self._current_node = opener

            # First turn: no transition needed
            if not state.messages:
                return opener["text"]

            transition = random.choice(_TRANSITIONS)
            return f"{transition} {opener['text']}"

        # No tree match — clear current node, fall back to LLM
        self._current_node = None
        return None

    def _generate_llm_message(self, state, guidance):
        """Generate a message using the LLM (original behavior)."""
        prompt = self._build_prompt(state, guidance)

        kwargs = {
            "temperature": self.temperature,
            "max_tokens": 500,
            "system_prompt": self.base_prompt,
        }
        if self.model:
            kwargs["model"] = self.model

        raw = llm.chat(prompt, **kwargs)
        return self._extract_message(raw)

    def _build_prompt(
        self,
        state: InterviewState,
        guidance: OrchestratorGuidance,
    ) -> str:
        """Build the user prompt for the interviewer LLM."""
        if state.messages:
            history = "\n".join(
                f"{'You' if m.role == 'interviewer' else 'Persona'}: {m.content}"
                for m in state.messages
            )
        else:
            history = "[This is the start of the conversation. You speak first.]"

        return (
            f"{guidance.guidance_text}\n\n"
            f"---\n\n"
            f"## Conversation So Far\n\n"
            f"{history}\n\n"
            f"---\n\n"
            f"Now generate your next message. Output ONLY the text of your "
            f"message to the persona. Do not include JSON, metadata, or reasoning."
        )

    def _extract_message(self, raw: str) -> str:
        """
        Extract the plain-text message from the LLM response.
        Strip any JSON or metadata the LLM might include despite instructions.
        """
        # If the response looks like JSON, try to extract a message field
        if raw.strip().startswith("{"):
            try:
                data = json.loads(raw)
                for key in ("message", "your_response", "response", "text"):
                    if key in data:
                        return data[key].strip()
            except json.JSONDecodeError:
                pass

        # Strip markdown code fences if present
        text = raw.strip()
        text = re.sub(r'^```(?:json)?\s*\n?', '', text)
        text = re.sub(r'\n?```\s*$', '', text)
        return text.strip()
